import { booleanExpressionToString, expressionToCircuit } from '../core';
import type { SolverResult, TruthTable } from '../core';
import { CircuitDiagram } from './CircuitDiagram';
import { KMap } from './KMap';
import { TruthTable as TruthTableView } from './TruthTable';

interface PrintReportProps {
  solution?: SolverResult | undefined;
  truthTable: TruthTable;
  minterms: readonly number[];
  maxterms: readonly number[];
  dontCares: readonly number[];
}
export function PrintReport({
  solution,
  truthTable,
  minterms,
  maxterms,
  dontCares,
}: PrintReportProps) {
  if (!solution) return null;
  const expression = booleanExpressionToString(solution.expression, solution.kMap.variables);
  return (
    <article className="print-report" aria-label="Printable solution report">
      <header>
        <h1>Karnaugh Map Solution</h1>
        <p>Generated by Karnaugh Studio</p>
      </header>
      <section className="print-summary">
        <h2>Function</h2>
        <dl>
          <div>
            <dt>Variables</dt>
            <dd>{solution.kMap.variables.map(({ name }) => name).join(', ')}</dd>
          </div>
          <div>
            <dt>Minterms</dt>
            <dd>Σm({minterms.join(', ')})</dd>
          </div>
          <div>
            <dt>Maxterms</dt>
            <dd>ΠM({maxterms.join(', ')})</dd>
          </div>
          <div>
            <dt>Don’t-cares</dt>
            <dd>d({dontCares.join(', ')})</dd>
          </div>
          <div>
            <dt>Simplified</dt>
            <dd>F = {expression}</dd>
          </div>
        </dl>
      </section>
      <section>
        <h2>Karnaugh map and selected groups</h2>
        <KMap groups={solution.groups} map={solution.kMap} onCycleCell={() => undefined} />
      </section>
      <section>
        <h2>Selected implicants</h2>
        <ol>
          {solution.groups.map((group) => (
            <li key={group.id}>
              <code>{booleanExpressionToString(group.term, solution.kMap.variables)}</code> — m(
              {group.coveredMinterms.join(', ')}){group.isEssential ? ' — essential' : ''}
            </li>
          ))}
        </ol>
      </section>
      <section>
        <h2>Step-by-step solution</h2>
        <ol>
          {solution.steps.map((step) => (
            <li key={step.id}>
              <strong>{step.title}</strong>
              <p>{step.description}</p>
            </li>
          ))}
        </ol>
      </section>
      <section className="print-table">
        <h2>Truth table</h2>
        <TruthTableView onCycleOutput={() => undefined} table={truthTable} />
      </section>
      <section className="print-circuit">
        <h2>Logic circuit</h2>
        <CircuitDiagram
          circuit={expressionToCircuit(solution.expression, solution.kMap.variables)}
        />
      </section>
    </article>
  );
}
